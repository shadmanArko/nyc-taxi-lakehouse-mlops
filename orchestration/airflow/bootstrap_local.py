"""Create the two local, gitignored files the Airflow stack needs.

    make airflow-bootstrap        (BUNDLE_TARGET=dev by default)

* ``.env``: generated Fernet/JWT keys + where things live, read from the deployed
  Databricks bundle (schema names, landing volume, job name, warehouse).
* ``secrets/connections.json`` (mode 600): Airflow connections. The Databricks token
  is asked for with a hidden prompt; the object-storage keys are copied from the
  ``taxi-dvc`` AWS profile. Nothing secret is printed.

Re-running keeps existing generated keys and asks again only for the token.
"""

import base64
import configparser
import getpass
import json
import os
import secrets
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

HERE = Path(__file__).parent
ENV_FILE = HERE / ".env"
CONNECTIONS = HERE / "secrets" / "connections.json"
AWS_PROFILE = os.environ.get("TAXI_AWS_PROFILE", "taxi-dvc")
TARGET = os.environ.get("BUNDLE_TARGET", "dev")


def bundle_summary() -> dict:  # type: ignore[type-arg]
    out = subprocess.run(  # noqa: S603
        ["databricks", "bundle", "summary", "-t", TARGET, "-o", "json"],  # noqa: S607
        cwd=HERE.parents[1],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)  # type: ignore[no-any-return]


def workspace_host(summary: dict) -> str:  # type: ignore[type-arg]
    """The bundle summary names the CLI profile; the host lives in ~/.databrickscfg."""
    if os.environ.get("DATABRICKS_HOST"):
        return os.environ["DATABRICKS_HOST"].rstrip("/")
    profile = summary["workspace"].get("profile") or "DEFAULT"
    cfg = configparser.ConfigParser()
    cfg.read(Path.home() / ".databrickscfg")
    return cfg[profile]["host"].rstrip("/")


def token_works(host: str, token: str) -> bool:
    """Ask Databricks who this token belongs to; never prints the token."""
    request = urllib.request.Request(  # noqa: S310 - host comes from the user's own config
        f"{host}/api/2.0/preview/scim/v2/Me", headers={"Authorization": f"Bearer {token}"}
    )
    try:
        with urllib.request.urlopen(request, timeout=20) as response:  # noqa: S310
            return bool(response.status == 200)
    except urllib.error.URLError:
        return False


def existing_env() -> dict[str, str]:
    if not ENV_FILE.exists():
        return {}
    pairs = (line.split("=", 1) for line in ENV_FILE.read_text().splitlines() if "=" in line)
    return {k: v for k, v in pairs if not k.startswith("#")}


def main() -> int:
    summary = bundle_summary()
    res, var = summary["resources"], summary["variables"]
    catalog = var["catalog"]["value"]
    job_name = res["jobs"]["taxi_medallion_refresh"]["name"]
    old = existing_env()
    env = {
        "AIRFLOW__CORE__FERNET_KEY": old.get("AIRFLOW__CORE__FERNET_KEY")
        or base64.urlsafe_b64encode(secrets.token_bytes(32)).decode(),
        "AIRFLOW__API_AUTH__JWT_SECRET": old.get("AIRFLOW__API_AUTH__JWT_SECRET")
        or secrets.token_urlsafe(48),
        "TAXI_CATALOG": catalog,
        "TAXI_GOLD_SCHEMA": res["schemas"]["gold"]["name"],
        "TAXI_LANDING_VOLUME": f"/Volumes/{catalog}/{res['schemas']['raw']['name']}/landing/yellow",
        "TAXI_DATABRICKS_JOB_NAME": job_name,
        "TAXI_SNAPSHOT_BUCKET": "taxi-dvc",
    }
    ENV_FILE.write_text(
        "# Generated by bootstrap_local.py - local only, gitignored.\n"
        + "".join(f"{k}={v}\n" for k, v in env.items())
    )
    ENV_FILE.chmod(0o600)

    aws = configparser.ConfigParser()
    aws.read(Path.home() / ".aws" / "credentials")
    if AWS_PROFILE not in aws:
        print(f"AWS profile [{AWS_PROFILE}] not found in ~/.aws/credentials", file=sys.stderr)
        return 1
    token = getpass.getpass("Databricks personal access token for Airflow (hidden): ").strip()
    if not token.startswith("dapi"):
        print("That does not look like a Databricks token (dapi...).", file=sys.stderr)
        return 1
    host = workspace_host(summary)
    if not token_works(host, token):
        print(f"Databricks rejected that token for {host}; nothing was written.", file=sys.stderr)
        return 1
    connections = {
        "databricks_default": {
            "conn_type": "databricks",
            "host": host,
            "password": token,
            "extra": {"warehouse_id": var["warehouse_id"]["value"]},
        },
        "taxi_storage": {
            "conn_type": "aws",
            "login": aws[AWS_PROFILE]["aws_access_key_id"],
            "password": aws[AWS_PROFILE]["aws_secret_access_key"],
            "extra": {"endpoint_url": "http://host.docker.internal:8333"},
        },
    }
    CONNECTIONS.parent.mkdir(exist_ok=True)
    CONNECTIONS.touch(mode=0o600)
    CONNECTIONS.chmod(0o600)
    CONNECTIONS.write_text(json.dumps(connections, indent=2) + "\n")
    print(
        f"wrote {ENV_FILE.name} and secrets/{CONNECTIONS.name} for target {TARGET!r} "
        f"(job: {job_name})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
